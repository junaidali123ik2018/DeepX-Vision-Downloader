def launch_browser(
    initial_url: str = "https://www.youtube.com",
    ipc_port: int | None = None,
    title: str = "DeepX Vision Browser",
    auto_close_after: float | None = None,
) -> None:
    """
    Launches the standalone In-App Chromium Browser window.
    Runs on the main thread of its dedicated process.
    """
    global _active_browser_window, _active_ipc_port
    _active_ipc_port = ipc_port

    api = BrowserBridge()
    storage_dir = get_browser_data_dir() / "browser_profile"
    storage_dir.mkdir(parents=True, exist_ok=True)

    window = webview.create_window(
        title=title,
        url=initial_url,
        js_api=api,
        width=1220,
        height=820,
        min_size=(820, 580),
    )
    _active_browser_window = window

    def on_page_loaded():
        script = _build_injection_script()
        try:
            window.evaluate_js(script)
        except Exception as e:
            print(f"[DeepX Browser] UI injection error: {e}", flush=True)

        # Trigger cookie sync on page load
        api.sync_cookies(window.get_current_url())

    window.events.loaded += on_page_loaded

    if auto_close_after and auto_close_after > 0:
        def _auto_destroy():
            time.sleep(auto_close_after)
            window.destroy()
        threading.Thread(target=_auto_destroy, daemon=True).start()

    def on_page_closing():
        try:
            api.sync_cookies(window.get_current_url())
        except Exception:
            pass
    window.events.closing += on_page_closing

    # Start Edge Chromium webview with persistent user profile and real Chrome user-agent
    webview.start(
        storage_path=str(storage_dir),
        private_mode=False,
        user_agent=CHROME_USER_AGENT,
    )


class BrowserIPCServer:
    """
    Lightweight localhost HTTP server running inside HQVideoDownloaderApp
    to receive download requests and cookie sync events from the In-App Browser.
    """

    def __init__(
        self,
        on_download: Callable[[str, str, str], None],
        on_cookies_synced: Callable[[str, str], None] | None = None,
        on_focus: Callable[[], None] | None = None,
    ):
        self.on_download = on_download
        self.on_cookies_synced = on_cookies_synced
        self.on_focus = on_focus
        self._server: http.server.HTTPServer | None = None
        self._thread: threading.Thread | None = None
        self.port: int = 0

    def start(self) -> int:
        outer = self

        class IPCHandler(http.server.BaseHTTPRequestHandler):
            def _send_cors_headers(self, code=200):
                self.send_response(code)
                self.send_header("Access-Control-Allow-Origin", "*")
                self.send_header("Access-Control-Allow-Methods", "POST, GET, OPTIONS")
                self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
                self.send_header("Content-Type", "application/json")
                self.end_headers()

            def do_OPTIONS(self):
                self._send_cors_headers(200)
                self.wfile.write(b'{"status":"ok"}')

            def do_POST(self):
                try:
                    content_len = int(self.headers.get("Content-Length", 0))
                    raw_body = self.rfile.read(content_len).decode("utf-8") if content_len > 0 else "{}"
                    data = json.loads(raw_body) if raw_body else {}
                    
                    if self.path == "/download":
                        url = data.get("url", "")
                        cookies_path = data.get("cookies_path", "")
                        title = data.get("title", "")
                        if url and outer.on_download:
                            outer.on_download(url, cookies_path, title)
                        self._send_cors_headers(200)
                        self.wfile.write(b'{"status":"ok"}')
                        return

                    elif self.path == "/sync_cookies":
                        platform = data.get("platform", "")
                        cookies_path = data.get("cookies_path", "")
                        if outer.on_cookies_synced:
                            outer.on_cookies_synced(platform, cookies_path)
                        self._send_cors_headers(200)
                        self.wfile.write(b'{"status":"ok"}')
                        return

                    elif self.path == "/focus":
                        if outer.on_focus:
                            outer.on_focus()
                        self._send_cors_headers(200)
                        self.wfile.write(b'{"status":"ok"}')
                        return

                except Exception as e:
                    print(f"[IPCServer] Error handling request: {e}", flush=True)

                self._send_cors_headers(400)
                self.wfile.write(b'{"status":"error"}')

            def log_message(self, format, *args):
                pass  # Suppress console HTTP access logs

        self._server = http.server.HTTPServer(("127.0.0.1", 0), IPCHandler)
        self.port = self._server.server_port
        try:
            (get_browser_data_dir() / "ipc_port.txt").write_text(str(self.port), encoding="utf-8")
        except Exception:
            pass
        self._thread = threading.Thread(target=self._server.serve_forever, daemon=True)
        self._thread.start()
        return self.port

    def stop(self) -> None:
        if self._server:
            try:
                self._server.shutdown()
                self._server.server_close()
            except Exception:
                pass


def get_installed_browsers() -> dict[str, str]:
    """
    Scans Windows system locations to detect installed browsers.
    Returns a dict mapping browser name to executable path.
    Supported browsers: Google Chrome, Microsoft Edge, Brave Browser, Mozilla Firefox.
    """
    local = os.environ.get("LOCALAPPDATA", "")
    prog_files = os.environ.get("ProgramFiles", "C:\\Program Files")
    prog_files_x86 = os.environ.get("ProgramFiles(x86)", "C:\\Program Files (x86)")

    candidates = {
        "Google Chrome": [
            Path(prog_files) / "Google" / "Chrome" / "Application" / "chrome.exe",
            Path(prog_files_x86) / "Google" / "Chrome" / "Application" / "chrome.exe",
            Path(local) / "Google" / "Chrome" / "Application" / "chrome.exe",
        ],
        "Microsoft Edge": [
            Path(prog_files_x86) / "Microsoft" / "Edge" / "Application" / "msedge.exe",
            Path(prog_files) / "Microsoft" / "Edge" / "Application" / "msedge.exe",
            Path(local) / "Microsoft" / "Edge" / "Application" / "msedge.exe",
        ],
        "Brave Browser": [
            Path(prog_files) / "BraveSoftware" / "Brave-Browser" / "Application" / "brave.exe",
            Path(prog_files_x86) / "BraveSoftware" / "Brave-Browser" / "Application" / "brave.exe",
            Path(local) / "BraveSoftware" / "Brave-Browser" / "Application" / "brave.exe",
        ],
        "Mozilla Firefox": [
            Path(prog_files) / "Mozilla Firefox" / "firefox.exe",
            Path(prog_files_x86) / "Mozilla Firefox" / "firefox.exe",
            Path(local) / "Mozilla Firefox" / "firefox.exe",
        ],
    }

    found: dict[str, str] = {}
    for name, paths in candidates.items():
        for p in paths:
            if p.is_file():
                found[name] = str(p)
                break
    return found


def get_isolated_profile_dir(browser_name: str = "Google Chrome") -> Path:
    """
    Returns the dedicated, isolated profile folder for the DeepX browser engine.
    Kept completely separate from personal browser profiles, inside LocalAppData/DeepX Vision Downloader.
    """
    base = get_browser_data_dir()
    if "firefox" in browser_name.lower():
        p_dir = base / "browser_profile_firefox"
    else:
        p_dir = base / "browser_profile"
    p_dir.mkdir(parents=True, exist_ok=True)
    return p_dir


def sync_profile_cookies_to_files(browser_name: str = "Google Chrome") -> None:
    """
    Safely exports authentication cookies from the isolated profile directory
    to Netscape format cookies_<platform>.txt files for downstream tools.
    """
    p_dir = get_isolated_profile_dir(browser_name)
    b_type = "firefox" if "firefox" in browser_name.lower() else (
        "brave" if "brave" in browser_name.lower() else (
            "edge" if "edge" in browser_name.lower() else "chrome"
        )
    )
    try:
        from yt_dlp.cookies import extract_cookies_from_browser
        jar = extract_cookies_from_browser(b_type, profile=str(p_dir))
        if jar:
            general_file = get_cookie_file_path("browser")
            jar.save(str(general_file), ignore_discard=True, ignore_expires=True)
            for plat in ["youtube", "instagram", "tiktok", "facebook", "x"]:
                dest = get_cookie_file_path(plat)
                jar.save(str(dest), ignore_discard=True, ignore_expires=True)
    except Exception:
        pass


