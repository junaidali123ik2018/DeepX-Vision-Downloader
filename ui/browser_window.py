def extract_post_media_headless(url: str) -> None:
    """
    CLI handler for: --media-extract <url>
    Renders post/page in hidden WebView2, extracts all high-res photos / carousel slides,
    and outputs JSON array of image objects to stdout.
    """
    storage_dir = get_browser_data_dir() / "browser_profile"
    result_images = []

    window = webview.create_window(
        title="Media Extractor",
        url=url,
        hidden=True,
        width=1000,
        height=800,
    )

    def on_loaded():
        nonlocal result_images
        time.sleep(2.5)
        try:
            js_code = """
            (function() {
                var items = [];
                var seen = {};

                // 1. Meta og:image
                var og = document.querySelector('meta[property="og:image"]');
                if (og && og.content) {
                    seen[og.content] = true;
                    items.push({ url: og.content, alt: 'Main Photo' });
                }

                // 2. Article / Post Images (carousels, photos)
                var imgs = document.querySelectorAll('article img, main img, div[role="dialog"] img');
                for (var i = 0; i < imgs.length; i++) {
                    var s = imgs[i].src;
                    if (!s || seen[s]) continue;
                    if (s.includes('/t51.82787-19/') || s.includes('/t51.75761-19/') || s.includes('/150x150/') || s.includes('/s150x150_')) continue;
                    var alt = imgs[i].alt || '';
                    if (alt.toLowerCase().includes('profile picture')) continue;
                    seen[s] = true;
                    items.push({ url: s, alt: alt || ('Slide ' + (items.length + 1)) });
                }
                var docTitle = document.title || 'Instagram Post';
                return {
                    title: docTitle,
                    items: items
                };
            })()
            """
            res = window.evaluate_js(js_code)
            if res and res.get("items"):
                title = res.get("title", "Post")
                for idx, it in enumerate(res["items"]):
                    result_images.append({
                        "url": it["url"],
                        "title": f"{title}_{idx+1}" if len(res["items"]) > 1 else title,
                        "ext": "jpg",
                    })
        except Exception:
            pass
        finally:
            window.destroy()

    window.events.loaded += on_loaded
    webview.start(
        storage_path=str(storage_dir),
        private_mode=False,
        user_agent=CHROME_USER_AGENT,
    )

    sys.stdout.buffer.write(json.dumps(result_images).encode("utf-8"))


