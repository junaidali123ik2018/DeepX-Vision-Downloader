def launch_browser(
    initial_url: str = "https://www.youtube.com",
    ipc_port: int | None = None,
    title: str = "DeepX Vision Browser",
    auto_close_after: float | None = None,
) -> None:
    """
    Launches the standalone In-App Chromium Browser window.
    Runs on the main thread of its dedicated process.
    """
    global _active_browser_window, _active_ipc_port
    _active_ipc_port = ipc_port

    api = BrowserBridge()
    storage_dir = get_browser_data_dir() / "browser_profile"
    storage_dir.mkdir(parents=True, exist_ok=True)

    window = webview.create_window(
        title=title,
        url=initial_url,
        js_api=api,
        width=1220,
        height=820,
        min_size=(820, 580),
    )
    _active_browser_window = window

    def on_page_loaded():
        script = _build_injection_script()
        try:
            window.evaluate_js(script)
        except Exception as e:
            print(f"[DeepX Browser] UI injection error: {e}", flush=True)

        # Trigger cookie sync on page load
        api.sync_cookies(window.get_current_url())

    window.events.loaded += on_page_loaded

    if auto_close_after and auto_close_after > 0:
        def _auto_destroy():
            time.sleep(auto_close_after)
            window.destroy()
        threading.Thread(target=_auto_destroy, daemon=True).start()

    def on_page_closing():
        try:
            api.sync_cookies(window.get_current_url())
        except Exception:
            pass
    window.events.closing += on_page_closing

    # Start Edge Chromium webview with persistent user profile and real Chrome user-agent
    webview.start(
        storage_path=str(storage_dir),
        private_mode=False,
        user_agent=CHROME_USER_AGENT,
    )


class BrowserIPCServer:
    """
    Lightweight localhost HTTP server running inside HQVideoDownloaderApp
    to receive download requests and cookie sync events from the In-App Browser.
    """

    def __init__(
        self,
        on_download: Callable[[str, str, str], None],
        on_cookies_synced: Callable[[str, str], None] | None = None,
        on_focus: Callable[[], None] | None = None,
    ):
        self.on_download = on_download
        self.on_cookies_synced = on_cookies_synced
        self.on_focus = on_focus
        self._server: http.server.HTTPServer | None = None
        self._thread: threading.Thread | None = None
        self.port: int = 0

    def start(self) -> int:
        outer = self

        class IPCHandler(http.server.BaseHTTPRequestHandler):
            def do_POST(self):
                try:
                    content_len = int(self.headers.get("Content-Length", 0))
                    raw_body = self.rfile.read(content_len).decode("utf-8") if content_len > 0 else "{}"
                    data = json.loads(raw_body) if raw_body else {}
                    
                    if self.path == "/download":
                        url = data.get("url", "")
                        cookies_path = data.get("cookies_path", "")
                        title = data.get("title", "")
                        if url and outer.on_download:
                            outer.on_download(url, cookies_path, title)
                        self.send_response(200)
                        self.end_headers()
                        self.wfile.write(b'{"status":"ok"}')
                        return

                    elif self.path == "/sync_cookies":
                        platform = data.get("platform", "")
                        cookies_path = data.get("cookies_path", "")
                        if outer.on_cookies_synced:
                            outer.on_cookies_synced(platform, cookies_path)
                        self.send_response(200)
                        self.end_headers()
                        self.wfile.write(b'{"status":"ok"}')
                        return

                    elif self.path == "/focus":
                        if outer.on_focus:
                            outer.on_focus()
                        self.send_response(200)
                        self.end_headers()
                        self.wfile.write(b'{"status":"ok"}')
                        return

                except Exception as e:
                    print(f"[IPCServer] Error handling request: {e}", flush=True)

                self.send_response(400)
                self.end_headers()
                self.wfile.write(b'{"status":"error"}')

            def log_message(self, format, *args):
                pass  # Suppress console HTTP access logs

        self._server = http.server.HTTPServer(("127.0.0.1", 0), IPCHandler)
        self.port = self._server.server_port
        self._thread = threading.Thread(target=self._server.serve_forever, daemon=True)
        self._thread.start()
        return self.port

    def stop(self) -> None:
        if self._server:
            try:
                self._server.shutdown()
                self._server.server_close()
            except Exception:
                pass


class BrowserManager:
    """Manages launching browser child processes from HQVideoDownloaderApp."""

    _active_process: subprocess.Popen | None = None

    @classmethod
    def open_browser(cls, url: str, ipc_port: int | None = None) -> None:
        """Launches the In-App Browser in a separate process."""
        clean_url = url.strip()
        if not clean_url:
            clean_url = "https://www.youtube.com"

        if getattr(sys, "frozen", False):
            # Running as compiled PyInstaller executable
            cmd = [sys.executable, "--browser", clean_url]
            if ipc_port:
                cmd.extend(["--port", str(ipc_port)])
        else:
            # Running from source
            main_script = str(Path(__file__).parent.parent / "main.py")
            cmd = [sys.executable, main_script, "--browser", clean_url]
            if ipc_port:
                cmd.extend(["--port", str(ipc_port)])

        try:
            cls._active_process = subprocess.Popen(
                cmd,
                creationflags=subprocess.DETACHED_PROCESS if sys.platform == "win32" else 0,
            )
        except Exception as ex:
            print(f"[BrowserManager] Failed to launch browser process: {ex}", flush=True)


def extract_instagram_profile_headless(username: str) -> None:
    """
    CLI handler for: --ig-extract <username>
    Runs in a dedicated process to render Instagram profile in hidden WebView2,
    extract posts and profile info, and output JSON to stdout.
    """
    storage_dir = get_browser_data_dir() / "browser_profile"
    clean_user = username.strip().lstrip("@").rstrip("/")
    target_url = f"https://www.instagram.com/{clean_user}/"

    result_data = None

    window = webview.create_window(
        title="IG Scraper",
        url=target_url,
        hidden=True,
        width=1000,
        height=800,
    )

    def on_loaded():
        nonlocal result_data
        time.sleep(2.5)  # Allow React client-side rendering
        try:
            # Sync cookies to file while page is active
            cookies = window.get_cookies()
            if cookies:
                export_cookies_to_netscape(cookies, get_cookie_file_path("instagram"))
                export_cookies_to_netscape(cookies, get_cookie_file_path("browser"))

            is_logged_in = False
            for c in (cookies or []):
                c_name = getattr(c, "name", "") if hasattr(c, "name") else c.get("name", "") if isinstance(c, dict) else str(c)
                if "sessionid" in str(c_name) or "ds_user_id" in str(c_name):
                    is_logged_in = True
                    break

            if not is_logged_in:
                ig_p = get_cookie_file_path("instagram")
                if ig_p.is_file():
                    content = ig_p.read_text(encoding="utf-8", errors="ignore")
                    if "sessionid" in content or "ds_user_id" in content:
                        is_logged_in = True

            all_posts = {}
            header_data = {}
            no_change_count = 0
            last_count = 0

            # If user is logged in, allow up to 80 scroll iterations to grab full account!
            # If guest, 4 iterations to check if more can be loaded.
            scroll_limit = 80 if is_logged_in else 4

            for step in range(scroll_limit):
                js_code = """
                (function() {
                    // 1. Dismiss any blocking dialogs
                    var dialogs = document.querySelectorAll('div[role="dialog"]');
                    for (var d = 0; d < dialogs.length; d++) {
                        var txt = dialogs[d].innerText || '';
                        if (txt.includes('Sign up') || txt.includes('Log In') || txt.includes('See photos')) {
                            var parent = dialogs[d].parentElement;
                            while (parent && parent !== document.body) {
                                if (window.getComputedStyle(parent).position === 'fixed') {
                                    parent.remove();
                                    break;
                                }
                                parent = parent.parentElement;
                            }
                            try { dialogs[d].remove(); } catch(e) {}
                        }
                    }

                    // 2. Extract profile header metadata
                    var metaDesc = document.querySelector('meta[name="description"]') ? document.querySelector('meta[name="description"]').content : '';
                    var totalM = metaDesc.match(/([\\d,KkMm.]+)\\s+Posts/i);
                    var totalPostsMeta = totalM ? totalM[1] : '';

                    var h2 = document.querySelector('header h2') || document.querySelector('header h1');
                    var headerImg = document.querySelector('header img');

                    // 3. Extract visible post links
                    var links = [];
                    var els = document.querySelectorAll('a[href*="/p/"], a[href*="/reel/"]');
                    for (var i = 0; i < els.length; i++) {
                        var href = els[i].href;
                        var img = els[i].querySelector('img');
                        var src = img ? img.src : null;
                        var alt = img ? img.alt : '';
                        var parts = href.split('/');
                        var id_str = parts[4] || ('ig_' + i);
                        links.push({
                            id: id_str,
                            url: href,
                            thumbnail: src,
                            thumbnail_url: src,
                            title: alt ? alt.substring(0, 80) : ('Instagram Post #' + (i + 1))
                        });
                    }

                    // 4. Scroll down using scrollview, window, and documentElement
                    var scroller = document.getElementById('scrollview') || 
                                   document.querySelector('div[id="scrollview"]') ||
                                   document.querySelector('div[style*="overflow-y: auto"]') ||
                                   document.querySelector('div[style*="overflow-y: scroll"]');
                    if (scroller) {
                        scroller.scrollTop = scroller.scrollHeight;
                    }
                    window.scrollBy(0, 1500);
                    window.scrollTo(0, document.documentElement.scrollHeight || document.body.scrollHeight);
                    window.dispatchEvent(new Event('scroll'));

                    return {
                        title: document.title,
                        uploader: h2 ? h2.textContent.trim() : '',
                        avatar: headerImg ? headerImg.src : null,
                        total_account_posts: totalPostsMeta,
                        posts: links
                    };
                })()
                """
                step_data = window.evaluate_js(js_code)
                if step_data:
                    if not header_data:
                        header_data = {
                            "title": step_data.get("title", ""),
                            "uploader": step_data.get("uploader", clean_user),
                            "avatar": step_data.get("avatar"),
                            "total_account_posts": step_data.get("total_account_posts", ""),
                        }
                    for p in step_data.get("posts", []):
                        if p["url"] not in all_posts:
                            all_posts[p["url"]] = p

                current_count = len(all_posts)
                if current_count == last_count:
                    no_change_count += 1
                    if no_change_count >= (5 if is_logged_in else 2):
                        break
                else:
                    no_change_count = 0
                    last_count = current_count

                time.sleep(1.5 if is_logged_in else 1.0)

            posts_list = list(all_posts.values())
            total_acc = header_data.get("total_account_posts", "")
            guest_capped = (not is_logged_in) and len(posts_list) <= 15

            result_data = {
                "title": header_data.get("title", clean_user),
                "uploader": header_data.get("uploader", clean_user),
                "avatar": header_data.get("avatar"),
                "total_account_posts": total_acc,
                "is_authenticated": is_logged_in,
                "guest_limit_reached": guest_capped,
                "count": len(posts_list),
                "posts": posts_list,
            }
        except Exception as e:
            pass
        finally:
            window.destroy()

    window.events.loaded += on_loaded
    webview.start(
        storage_path=str(storage_dir),
        private_mode=False,
        user_agent=CHROME_USER_AGENT,
    )

    output = result_data or {"count": 0, "posts": []}
    sys.stdout.buffer.write(json.dumps(output).encode("utf-8"))


