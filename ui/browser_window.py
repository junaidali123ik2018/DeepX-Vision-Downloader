def get_browser_data_dir() -> Path:
    """Returns persistent directory for DeepX Vision Downloader browser cache and cookies."""
    appdata = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~")
    base_dir = Path(appdata) / "DeepX Vision Downloader"
    base_dir.mkdir(parents=True, exist_ok=True)
    return base_dir


