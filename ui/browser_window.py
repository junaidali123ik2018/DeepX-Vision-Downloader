def get_cookie_file_path(platform: str = "browser") -> Path:
    """Returns the Netscape cookie file path for a given platform."""
    clean_p = platform.lower().replace(" ", "_")
    if clean_p in {"twitter", "x"}:
        clean_p = "x"
    return get_browser_data_dir() / f"cookies_{clean_p}.txt"


def detect_platform_from_url(url: str) -> str:
    """Determines the platform from a URL."""
    u = url.lower()
    if any(k in u for k in ["youtube.com", "youtu.be", "google.com", "accounts.google"]):
        return "youtube"
    if "instagram.com" in u:
        return "instagram"
    if "tiktok.com" in u:
        return "tiktok"
    if any(k in u for k in ["facebook.com", "fb.watch", "fb.com", "messenger.com"]):
        return "facebook"
    if any(k in u for k in ["twitter.com", "x.com", "t.co"]):
        return "x"
    if "soundcloud.com" in u:
        return "soundcloud"
    if "twitch.tv" in u:
        return "twitch"
    if "vimeo.com" in u:
        return "vimeo"
    if "dailymotion.com" in u:
        return "dailymotion"
    if "moviebox" in u:
        return "moviebox"
    if "watch-movies" in u:
        return "watchmoviespk"
    if "videodownloader.site" in u or "omnisave" in u:
        return "videodownloader"
    return "browser"


def export_cookies_to_netscape(cookies: list, dest_path: Path) -> int:
    """
    Exports a list of SimpleCookie or dict objects to standard Netscape cookie file format.
    Merges with any existing cookies in dest_path so multi-domain logins (e.g. google.com + youtube.com)
    are preserved without erasing previous valid tokens.
    Returns the number of cookies written.
    """
    cookie_map: dict[tuple[str, str, str], str] = {}
    now = int(time.time())

    # 1. Read existing cookies if file exists to prevent erasing previously authenticated domains
    if dest_path.is_file():
        try:
            for line in dest_path.read_text(encoding="utf-8", errors="ignore").splitlines():
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) >= 7:
                    dom, sub, path, sec, exp, name, val = parts[:7]
                    cookie_map[(dom.lower(), path, name)] = f"{dom}\t{sub}\t{path}\t{sec}\t{exp}\t{name}\t{val}\n"
        except Exception:
            pass

    # 2. Add / update with new cookies
    for cookie_obj in cookies:
        try:
            items = cookie_obj.items() if hasattr(cookie_obj, "items") else []
            for morsel_key, morsel in items:
                domain = morsel["domain"] or ""
                if not domain:
                    continue
                include_sub = "TRUE" if domain.startswith(".") else "FALSE"
                path = morsel["path"] or "/"
                secure = "TRUE" if morsel["secure"] else "FALSE"

                raw_exp = morsel["expires"]
                if raw_exp:
                    try:
                        expires = int(time.mktime(time.strptime(raw_exp, "%a, %d %b %Y %H:%M:%S GMT")))
                    except Exception:
                        expires = now + 86400 * 365
                else:
                    expires = now + 86400 * 365

                val = str(morsel.value or "")
                cookie_map[(domain.lower(), path, morsel_key)] = (
                    f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires}\t{morsel_key}\t{val}\n"
                )
        except Exception:
            continue

    if cookie_map:
        try:
            dest_path.parent.mkdir(parents=True, exist_ok=True)
            lines = ["# Netscape HTTP Cookie File\n# Generated by DeepX Vision Downloader\n\n"]
            lines.extend(cookie_map.values())
            with open(dest_path, "w", encoding="utf-8") as f:
                f.writelines(lines)
            return len(cookie_map)
        except Exception as ex:
            print(f"[DeepX Browser] Error writing cookies to {dest_path}: {ex}", flush=True)

    return 0


_active_browser_window: webview.Window | None = None
_active_ipc_port: int | None = None


class BrowserBridge:
    """Exposed JS API bridge accessible inside webview as window.pywebview.api."""

    def download_current(self, url: str | None = None) -> dict:
        global _active_browser_window, _active_ipc_port
        target_url = url
        if not target_url and _active_browser_window:
            target_url = _active_browser_window.get_current_url()

        if not target_url:
            return {"status": "error", "message": "No URL detected"}

        platform = detect_platform_from_url(target_url)
        cookie_file = get_cookie_file_path(platform)
        browser_cookie_file = get_cookie_file_path("browser")

        # Extract and save cookies
        if _active_browser_window:
            try:
                cookies = _active_browser_window.get_cookies()
                if cookies:
                    export_cookies_to_netscape(cookies, cookie_file)
                    export_cookies_to_netscape(cookies, browser_cookie_file)
            except Exception as e:
                print(f"[DeepX Browser] Error extracting cookies: {e}", flush=True)

        # Notify main application via IPC
        if _active_ipc_port:
            try:
                payload = {
                    "action": "download",
                    "url": target_url,
                    "platform": platform,
                    "cookies_path": str(cookie_file) if cookie_file.exists() else "",
                    "title": (_active_browser_window.title if _active_browser_window else "") or "",
                }
                req = urllib.request.Request(
                    f"http://127.0.0.1:{_active_ipc_port}/download",
                    data=json.dumps(payload).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                )
                with urllib.request.urlopen(req, timeout=3) as resp:
                    pass
            except Exception as ex:
                print(f"[DeepX Browser] IPC send failed: {ex}", flush=True)

        return {"status": "ok", "url": target_url}

    def sync_cookies(self, url: str | None = None) -> dict:
        global _active_browser_window, _active_ipc_port
        if not _active_browser_window:
            return {"status": "error"}

        curr_url = url or _active_browser_window.get_current_url() or ""
        platform = detect_platform_from_url(curr_url)
        cookie_file = get_cookie_file_path(platform)
        browser_cookie_file = get_cookie_file_path("browser")

        try:
            cookies = _active_browser_window.get_cookies()
            if cookies:
                export_cookies_to_netscape(cookies, cookie_file)
                export_cookies_to_netscape(cookies, browser_cookie_file)
                if platform == "youtube" or "google.com" in curr_url.lower():
                    export_cookies_to_netscape(cookies, get_cookie_file_path("youtube"))
                if platform in {"x", "twitter"} or "x.com" in curr_url.lower():
                    export_cookies_to_netscape(cookies, get_cookie_file_path("x"))

                if _active_ipc_port:
                    payload = {
                        "action": "sync_cookies",
                        "platform": platform,
                        "cookies_path": str(cookie_file),
                    }
                    req = urllib.request.Request(
                        f"http://127.0.0.1:{_active_ipc_port}/sync_cookies",
                        data=json.dumps(payload).encode("utf-8"),
                        headers={"Content-Type": "application/json"},
                    )
                    with urllib.request.urlopen(req, timeout=3) as resp:
                        pass
        except Exception as e:
            print(f"[DeepX Browser] Sync cookies error: {e}", flush=True)

        return {"status": "ok"}

    def close_browser(self) -> dict:
        global _active_browser_window, _active_ipc_port
        try:
            self.sync_cookies()
        except Exception:
            pass

        # Notify main app to bring itself to front
        if _active_ipc_port:
            try:
                payload = {"action": "focus_main"}
                req = urllib.request.Request(
                    f"http://127.0.0.1:{_active_ipc_port}/focus",
                    data=json.dumps(payload).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                )
                with urllib.request.urlopen(req, timeout=2) as resp:
                    pass
            except Exception:
                pass

        if _active_browser_window:
            try:
                # Destroy window on a slight timer so JS promise resolves cleanly
                threading.Timer(0.1, lambda: _active_browser_window.destroy()).start()
            except Exception:
                pass
        return {"status": "ok"}

    def focus_main(self) -> dict:
        global _active_ipc_port
        if _active_ipc_port:
            try:
                payload = {"action": "focus_main"}
                req = urllib.request.Request(
                    f"http://127.0.0.1:{_active_ipc_port}/focus",
                    data=json.dumps(payload).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                )
                with urllib.request.urlopen(req, timeout=2) as resp:
                    pass
            except Exception:
                pass
        return {"status": "ok"}


