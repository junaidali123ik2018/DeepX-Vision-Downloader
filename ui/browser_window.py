def launch_isolated_browser(
    url: str = "https://www.youtube.com",
    browser_name: str | None = None,
    ipc_port: int | None = None,
) -> subprocess.Popen | None:
    """
    Launches the chosen installed browser in a dedicated standalone app window
    with an isolated profile stored inside the software's directory.
    - Completely unlinked from personal Chrome / profile picker.
    - Uses --app=<url> for a clean standalone window (no address bar clutter).
    - Injects DeepX Helper extension with 1-click Download buttons and card controls.
    - Native hardware-encrypted passwords and cookies (DPAPI) stored in local profile.
    """
    clean_url = url.strip()
    if not clean_url:
        clean_url = "https://www.youtube.com"
    if not clean_url.startswith("http://") and not clean_url.startswith("https://"):
        clean_url = f"https://{clean_url}"

    installed = get_installed_browsers()
    target_name = browser_name or "Google Chrome"

    # Fallback to any installed browser if selected one is not available
    if target_name not in installed:
        for pref in ["Google Chrome", "Microsoft Edge", "Brave Browser", "Mozilla Firefox"]:
            if pref in installed:
                target_name = pref
                break
        else:
            if installed:
                target_name = next(iter(installed))
            else:
                target_name = None

    if not target_name or target_name not in installed:
        # Fallback to WebView2 if no standalone browser executable was found
        print(f"[DeepX Browser] No standalone browser found, falling back to built-in webview.", flush=True)
        try:
            return subprocess.Popen(
                [sys.executable, "--browser", clean_url] if getattr(sys, "frozen", False) else [sys.executable, str(Path(__file__).parent.parent / "main.py"), "--browser", clean_url],
                creationflags=subprocess.DETACHED_PROCESS if sys.platform == "win32" else 0,
            )
        except Exception:
            return None

    exe_path = installed[target_name]
    profile_dir = get_isolated_profile_dir(target_name)

    is_firefox = "firefox" in target_name.lower()
    if is_firefox:
        cmd = [
            exe_path,
            "-profile", str(profile_dir),
            "-no-remote",
            clean_url,
        ]
    else:
        # Chromium (Chrome, Edge, Brave)
        ext_dir = ensure_browser_extension(ipc_port or 0)
        cmd = [
            exe_path,
            f"--user-data-dir={profile_dir}",
            f"--app={clean_url}",
            f"--load-extension={ext_dir}",
            f"--disable-extensions-except={ext_dir}",
            "--no-first-run",
            "--no-default-browser-check",
            "--disable-features=Translate",
            "--window-size=1280,820",
        ]

    try:
        proc = subprocess.Popen(
            cmd,
            creationflags=subprocess.DETACHED_PROCESS if sys.platform == "win32" else 0,
        )

        def _bg_sync():
            time.sleep(6)
            sync_profile_cookies_to_files(target_name)

        threading.Thread(target=_bg_sync, daemon=True).start()
        return proc
    except Exception as ex:
        print(f"[DeepX Browser] Failed to launch isolated {target_name}: {ex}", flush=True)
        return None


class BrowserManager:
    """Manages launching isolated browser child processes from HQVideoDownloaderApp."""

    _active_process: subprocess.Popen | None = None

    @classmethod
    def open_browser(
        cls,
        url: str,
        ipc_port: int | None = None,
        browser_name: str | None = None,
    ) -> None:
        """Launches the In-App Isolated Profile Browser in a dedicated app window."""
        cls._active_process = launch_isolated_browser(
            url=url,
            browser_name=browser_name,
            ipc_port=ipc_port,
        )


def extract_instagram_profile_headless(username: str) -> None:
    """
    CLI handler for: --ig-extract <username>
    Runs in a dedicated process to render Instagram profile in hidden WebView2,
    extract posts and profile info, and output JSON to stdout.
    """
    storage_dir = get_browser_data_dir() / "browser_profile"
    clean_user = username.strip().lstrip("@").rstrip("/")
    target_url = f"https://www.instagram.com/{clean_user}/"

    result_data = None

    window = webview.create_window(
        title="IG Scraper",
        url=target_url,
        hidden=True,
        width=1000,
        height=800,
    )

    def on_loaded():
        nonlocal result_data
        time.sleep(2.5)  # Allow React client-side rendering
        try:
            # Sync cookies to file while page is active
            cookies = window.get_cookies()
            if cookies:
                export_cookies_to_netscape(cookies, get_cookie_file_path("instagram"))
                export_cookies_to_netscape(cookies, get_cookie_file_path("browser"))

            is_logged_in = False
            for c in (cookies or []):
                c_name = getattr(c, "name", "") if hasattr(c, "name") else c.get("name", "") if isinstance(c, dict) else str(c)
                if "sessionid" in str(c_name) or "ds_user_id" in str(c_name):
                    is_logged_in = True
                    break

            if not is_logged_in:
                ig_p = get_cookie_file_path("instagram")
                if ig_p.is_file():
                    content = ig_p.read_text(encoding="utf-8", errors="ignore")
                    if "sessionid" in content or "ds_user_id" in content:
                        is_logged_in = True

            all_posts = {}
            header_data = {}
            no_change_count = 0
            last_count = 0

            # If user is logged in, allow up to 80 scroll iterations to grab full account!
            # If guest, 4 iterations to check if more can be loaded.
            scroll_limit = 80 if is_logged_in else 4

            for step in range(scroll_limit):
                js_code = """
                (function() {
                    // 1. Dismiss any blocking dialogs
                    var dialogs = document.querySelectorAll('div[role="dialog"]');
                    for (var d = 0; d < dialogs.length; d++) {
                        var txt = dialogs[d].innerText || '';
                        if (txt.includes('Sign up') || txt.includes('Log In') || txt.includes('See photos')) {
                            var parent = dialogs[d].parentElement;
                            while (parent && parent !== document.body) {
                                if (window.getComputedStyle(parent).position === 'fixed') {
                                    parent.remove();
                                    break;
                                }
                                parent = parent.parentElement;
                            }
                            try { dialogs[d].remove(); } catch(e) {}
                        }
                    }

                    // 2. Extract profile header metadata
                    var metaDesc = document.querySelector('meta[name="description"]') ? document.querySelector('meta[name="description"]').content : '';
                    var totalM = metaDesc.match(/([\\d,KkMm.]+)\\s+Posts/i);
                    var totalPostsMeta = totalM ? totalM[1] : '';

                    var h2 = document.querySelector('header h2') || document.querySelector('header h1');
                    var headerImg = document.querySelector('header img');

                    // 3. Extract visible post links
                    var links = [];
                    var els = document.querySelectorAll('a[href*="/p/"], a[href*="/reel/"]');
                    for (var i = 0; i < els.length; i++) {
                        var href = els[i].href;
                        var img = els[i].querySelector('img');
                        var src = img ? img.src : null;
                        var alt = img ? img.alt : '';
                        var parts = href.split('/');
                        var id_str = parts[4] || ('ig_' + i);
                        links.push({
                            id: id_str,
                            url: href,
                            thumbnail: src,
                            thumbnail_url: src,
                            title: alt ? alt.substring(0, 80) : ('Instagram Post #' + (i + 1))
                        });
                    }

                    // 4. Scroll down using scrollview, window, and documentElement
                    var scroller = document.getElementById('scrollview') || 
                                   document.querySelector('div[id="scrollview"]') ||
                                   document.querySelector('div[style*="overflow-y: auto"]') ||
                                   document.querySelector('div[style*="overflow-y: scroll"]');
                    if (scroller) {
                        scroller.scrollTop = scroller.scrollHeight;
                    }
                    window.scrollBy(0, 1500);
                    window.scrollTo(0, document.documentElement.scrollHeight || document.body.scrollHeight);
                    window.dispatchEvent(new Event('scroll'));

                    return {
                        title: document.title,
                        uploader: h2 ? h2.textContent.trim() : '',
                        avatar: headerImg ? headerImg.src : null,
                        total_account_posts: totalPostsMeta,
                        posts: links
                    };
                })()
                """
                step_data = window.evaluate_js(js_code)
                if step_data:
                    if not header_data:
                        header_data = {
                            "title": step_data.get("title", ""),
                            "uploader": step_data.get("uploader", clean_user),
                            "avatar": step_data.get("avatar"),
                            "total_account_posts": step_data.get("total_account_posts", ""),
                        }
                    for p in step_data.get("posts", []):
                        if p["url"] not in all_posts:
                            all_posts[p["url"]] = p

                current_count = len(all_posts)
                if current_count == last_count:
                    no_change_count += 1
                    if no_change_count >= (5 if is_logged_in else 2):
                        break
                else:
                    no_change_count = 0
                    last_count = current_count

                time.sleep(1.5 if is_logged_in else 1.0)

            posts_list = list(all_posts.values())
            total_acc = header_data.get("total_account_posts", "")
            guest_capped = (not is_logged_in) and len(posts_list) <= 15

            result_data = {
                "title": header_data.get("title", clean_user),
                "uploader": header_data.get("uploader", clean_user),
                "avatar": header_data.get("avatar"),
                "total_account_posts": total_acc,
                "is_authenticated": is_logged_in,
                "guest_limit_reached": guest_capped,
                "count": len(posts_list),
                "posts": posts_list,
            }
        except Exception as e:
            pass
        finally:
            window.destroy()

    window.events.loaded += on_loaded
    webview.start(
        storage_path=str(storage_dir),
        private_mode=False,
        user_agent=CHROME_USER_AGENT,
    )

    output = result_data or {"count": 0, "posts": []}
    sys.stdout.buffer.write(json.dumps(output).encode("utf-8"))


